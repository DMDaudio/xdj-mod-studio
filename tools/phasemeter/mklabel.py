#!/usr/bin/env python3
"""Render the MASTER CLOCK label + hexagon emblem to pm_label.h (alpha 0..32)."""
import math
import os
from PIL import Image, ImageDraw, ImageFont
W, H, X, Y = 86, 30, 172, 116
S = 4                                             # supersample
im = Image.new("L", (W * S, H * S), 0)
d = ImageDraw.Draw(im)
f = ImageFont.truetype("/System/Library/Fonts/HelveticaNeue.ttc", 11 * S, index=1)
for txt, ty in (("MASTER", 2), ("CLOCK", 15)):
    tw = d.textlength(txt, font=f)
    d.text((58 * S - tw, ty * S - 2 * S), txt, font=f, fill=255)
cx, cy, r = 73 * S, 15 * S, 10 * S
pts = [(cx + r * math.cos(math.radians(60 * i + 30)), cy + r * math.sin(math.radians(60 * i + 30)))
       for i in range(6)]
d.polygon(pts, outline=255, width=2 * S)
d.ellipse((cx - 4.5 * S, cy - 4.5 * S, cx + 4.5 * S, cy + 4.5 * S), outline=255, width=2 * S)
d.line((cx, cy + 4 * S, cx, cy + 9 * S), fill=255, width=2 * S)
im = im.resize((W, H), Image.LANCZOS)
a = [min(32, (v * 33) >> 8) for v in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())]
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "pm_label.h"), "w") as fo:
    fo.write(f"/* generated by mklabel.py */\n#define LABEL_X {X}\n#define LABEL_Y {Y}\n"
             f"#define LABEL_W {W}\n#define LABEL_H {H}\nstatic const unsigned char label_alpha[] = {{\n")
    for i in range(0, len(a), 30):
        fo.write("  " + ",".join(map(str, a[i:i + 30])) + ",\n")
    fo.write("};\n")
im.point(lambda v: v).save(os.path.join(here, "label_preview.png"))
print("pm_label.h", W, "x", H)
