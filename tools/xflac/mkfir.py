#!/usr/bin/env python3
"""mkfir.py -> tools/xflac/vf_fir.h: windowed-sinc decimation low-pass
filters for hi-res FLAC (88.2/96 kHz -> /2, 176.4/192 kHz -> /4), Q15,
taps summing exactly to 32768. Cut-off 0.45 of the OUTPUT Nyquist band
edge region (fs_out * 0.45), Blackman window."""
import math
import os


def taps(D, n):
    fc = 0.5 / D * 0.9                       # cycles per input sample
    h = []
    for i in range(n):
        m = i - (n - 1) / 2
        s = 2 * fc if m == 0 else math.sin(2 * math.pi * fc * m) / (math.pi * m)
        w = 0.42 - 0.5 * math.cos(2 * math.pi * i / (n - 1)) + 0.08 * math.cos(4 * math.pi * i / (n - 1))
        h.append(s * w)
    t = sum(h)
    q = [round(x / t * 32768) for x in h]
    q[(n - 1) // 2] += 32768 - sum(q)        # exact unity DC gain
    return q


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vf_fir.h")
with open(out, "w") as f:
    f.write("/* generated by mkfir.py: decimation low-pass, Q15, unity DC */\n")
    for D, n in ((2, 47), (4, 95)):
        q = taps(D, n)
        f.write(f"#define FIR{D}_N {n}\nstatic const short fir{D}[{n}] = {{{', '.join(map(str, q))}}};\n")
print(out)
